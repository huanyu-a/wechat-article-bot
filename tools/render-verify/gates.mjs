/**
 * 验收脚本的**退出码口径**（第二十九轮 E1）。
 *
 * 起因：第二十九轮 A 的全库审计查出——**九步链 15 个步骤里只有 1/9 的构建真正能判红**，
 * 其余 14 步（2/9~9g）全部没有退出码，脚本只要不抛异常就 `exit 0`。
 * 于是「九步 EXIT=0」被读成了「九步全通过」，而它当时的真实含义只是「九个脚本都没抛异常」。
 * 本支把那 14 步的结论各自变成一个数。
 *
 * 三条设计约束（都是为了不再制造「看起来是闸、其实是打印」的东西）：
 *
 *   1. **判据必须是纯函数** `判(数据) → 失败项[]`，主流程与 `--selftest` 走**同一个函数**。
 *      自检另写一套「看起来一样」的比较器不算数——那正是第二十九轮 A 在第 12/15 行抓到的毛病。
 *   2. **失败项说的是脚本自己已经算出来的量**（`fail` 数、`dangling` 数、`doubtful` 数、
 *      收集完整性…），本支**不新增任何判据**，只把既有结论接上退出码。
 *   3. **判红要说清是哪一项**。退出码 1 配上「失败项 N」＋逐项明细，人才知道去查什么。
 *
 * 与既有做法的关系：`r26-table-colwidth-exit.mjs` 第二十五轮就把「反例自检」写进了脚本本体，
 * `r26-leading-ws-effect.mjs` / `r25-save-exit-roundtrip.mjs` / `r16-compare-probe-vs-live.mjs`
 * 第二十九轮各立了 `--selftest`。本支把那套做法收敛成一个共同入口。
 */

/** 失败项：`{ 项, 详情 }`。`项` 要能一行说清是什么，`详情`给出数字。 */
export const 失败 = (项, 详情) => ({ 项, 详情 })

/**
 * 跑一次判据并把它打成一段人看得懂的输出。返回**失败项个数**。
 *
 * ⚠️ 不要在这里 `process.exit`：这些脚本末尾都还有 `close()` / `server.close()` 要跑，
 *    提前退出会把收尾跳过去（第二十九轮之前 `r26-leading-ws-effect` 就是这么写的，
 *    它没有浏览器收尾所以没事，别照抄到别的脚本上）。返回数字，由调用方 `process.exitCode = …`。
 */
export function 判据(步骤, 判, 数据, { 上限 = 20 } = {}) {
  const 清单 = 判(数据) || []
  console.log('')
  console.log('[闸] ' + 步骤 + ' · 失败项 ' + 清单.length)
  for (const 条 of 清单.slice(0, 上限)) console.log('   ❌ ' + 条.项 + '：' + 条.详情)
  if (清单.length > 上限) console.log('   …另有 ' + (清单.length - 上限) + ' 项')
  if (!清单.length) console.log('   ✅ 无失败项')
  return 清单.length
}

/**
 * `--selftest`：拿**同一把判据**跑几条已知好 / 已知坏的输入，证明闸是活的。
 *
 * 每条用例给 `{ 名, 数据, 期望 }`，`期望` 是 0（判绿）或 1（判红）。
 * 任何一条不符就返回 1 —— **包括「坏输入判绿」和「好输入判红」两个方向**：
 * 只证「抓住坏版本」不够，误报同样会让这个闸不可用。
 *
 * ⚠️ 用例里的「坏输入」必须是**真的坏**：改一个叶子值 / 拿掉一条记录 /
 *    用存档的旧版本，不是造一个语义等价的假货。
 */
export function 自检(步骤, 判, 用例) {
  console.log('[闸自检] ' + 步骤)
  let 全对 = true
  for (const 条 of 用例) {
    const 个数 = (判(条.数据) || []).length
    const 实际 = 个数 ? 1 : 0
    const 相符 = 实际 === 条.期望
    全对 = 全对 && 相符
    console.log('  ' + 条.名 + '：失败项 ' + 个数 + '（期望' + (条.期望 ? '**判红**' : '判绿') + '）'
      + (相符 ? ' ✅' : ' ❌ **闸写松了**') + (条.备注 ? ' · ' + 条.备注 : ''))
  }
  console.log(全对 ? '→ 闸是活的：坏输入判红、好输入不误报。'
    : '→ **自检不通过**：本支的判据与上面任一条不符，必须查。')
  return 全对 ? 0 : 1
}

/**
 * 「收集器」类脚本（2/9~6/9、8/9）共用的判据：**这一轮该收的证据，真的收齐了吗**。
 *
 * 这五支脚本自己不算 pass/fail（判定在 9a~9g 的汇总层），它们只负责把真实浏览器里的量落盘。
 * 它们能判红的东西只有三类，都是脚本本来就在控制台印出来的数：
 *   - **条数**对不上 => 有样例根本没渲染出来（或者重复渲染），后面所有汇总都少算；
 *   - **截图失败** => 那一行没有图，等于这一条没取证（图本身就是断言的一部分）；
 *   - **图片加载失败** => 产物里的图没解码，量到的盒子与拍到的图都不是真的
 *     （第十六轮就是这么翻的车：SVG 盒子对、截图却是白的）。
 * ⚠️ 上游层的问题（`:::` 残留、`nested-unsupported`）**不进这里**——与 9b/9c/9d/9e 同口径。
 */
export function 收集器判据(应有条数, 名 = '样例') {
  return ({ 条数, 截图失败 = 0, 图片失败 = 0, 图片总数 = 0 }) => {
    const 清单 = []
    if (条数 !== 应有条数) {
      清单.push(失败(名 + '数', 条数 + ' 条，应为 ' + 应有条数 + ' 条——'
        + (条数 < 应有条数 ? '有' + 名 + '没渲染出来' : '多出' + 名)))
    }
    if (截图失败) {
      清单.push(失败('截图失败', 截图失败 + ' 张没截到——图上没有证据，等于这一条没取证'))
    }
    if (图片失败) {
      清单.push(失败('图片加载失败', 图片失败 + ' / ' + 图片总数 + ' 张——图没解码，量到的盒子与截图都不是真的'))
    }
    return 清单
  }
}

/**
 * 收集器的 `--selftest`：拿**同一把判据**跑「当前存档 + 四种已知坏输入」。
 * `当前` 由调用方从刚落盘的产物里读出来，所以「好输入不误报」这一条验的是真数据。
 */
export function 收集器自检(步骤, 名, 应有条数, 当前) {
  const 判 = 收集器判据(应有条数, 名)
  return 自检(步骤, 判, [
    { 名: '当前存档（' + 当前.条数 + ' 条 / 截图失败 ' + 当前.截图失败 + ' / 图片失败 ' + 当前.图片失败 + '）',
      数据: 当前, 期望: 0, 备注: '应为 ' + 应有条数 + ' 条' },
    { 名: 名 + '少收一条', 数据: { ...当前, 条数: 当前.条数 - 1 }, 期望: 1, 备注: (当前.条数 - 1) + ' 条' },
    { 名: 名 + '多收一条（重复渲染）', 数据: { ...当前, 条数: 当前.条数 + 1 }, 期望: 1, 备注: (当前.条数 + 1) + ' 条' },
    { 名: '有一张截图没截到', 数据: { ...当前, 截图失败: 1 }, 期望: 1, 备注: '图上没有证据' },
    { 名: '有一张图加载失败', 数据: { ...当前, 图片失败: 1, 图片总数: Math.max(1, 当前.图片总数) }, 期望: 1, 备注: '盒子与截图都不可信' },
    { 名: '一条都没收到（退化输入）', 数据: { ...当前, 条数: 0 }, 期望: 1, 备注: '空输入不许判绿' },
  ])
}

/** 深拷贝一份数据，供自检造坏输入用（不改原对象）。 */
export const 克隆 = (数据) => JSON.parse(JSON.stringify(数据))

/**
 * 在深拷贝上改一个叶子值，`+增量`。用来造「已知坏输入」。
 *
 * 找的是**第一个数值叶子**——与 `r25-save-exit-roundtrip.mjs --selftest`、
 * `r16-compare-probe-vs-live.mjs --selftest` 里的做法一致（三处都改第一个数值叶子，
 * 是为了让「改了什么」能一行说清）。
 */
export function 改一个叶子(数据, 增量 = 1, 跳过 = () => false, 路径 = '') {
  if (!数据 || typeof 数据 !== 'object') return null
  for (const 键 of Object.keys(数据)) {
    const 值 = 数据[键]
    const 在 = 路径 ? 路径 + '.' + 键 : 键
    if (跳过(在, 值)) continue
    if (typeof 值 === 'number') {
      数据[键] = 值 + 增量
      return { 在, 原值: 值, 新值: 值 + 增量 }
    }
    if (值 && typeof 值 === 'object') {
      const 命中 = 改一个叶子(值, 增量, 跳过, 在)
      if (命中) return 命中
    }
  }
  return null
}
